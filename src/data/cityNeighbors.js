/** @param {string} citySlug */
export function getNearbyCitySlugs(citySlug) {
  const all = Object.keys(citiesMap).filter(
    (c) => c !== "south-florida" && c !== citySlug,
  );
  const preferred = [...(CITY_NEIGHBORS[citySlug] || [])].filter(
    (s) => s !== citySlug && citiesMap[s],
  );
  const seen = new Set(preferred);
  const rest = all.filter((s) => !seen.has(s)).sort();
  return [...preferred, ...rest].slice(0, 8);
}
